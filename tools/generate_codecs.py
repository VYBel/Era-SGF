#!/usr/bin/env python3
"""Generate Unicode mapping data using Python's standard codec tables."""
from pathlib import Path

out = ['// Generated by tools/generate_codecs.py; undefined bytes use 0xFFFD.']
for name, codec in [('cp1251', 'cp1251'), ('koi8r', 'koi8_r'), ('cp866', 'cp866'), ('iso88595', 'iso8859_5')]:
    values = []
    for byte in range(128, 256):
        try:
            values.append(ord(bytes([byte]).decode(codec)))
        except UnicodeDecodeError:
            values.append(0xFFFD)
    out.append(f'static constexpr char32_t {name}[128] = {{')
    for start in range(0, 128, 8):
        out.append('    ' + ', '.join(f'0x{v:04X}' for v in values[start:start + 8]) + ',')
    out.append('};')
Path(__file__).resolve().parents[1].joinpath('src/codec_tables.inc').write_text('\n'.join(out) + '\n')
